export function localizeDestination(
  destination: Destination,
  locale: Locale,
): Destination {
  if (locale === "en") return destination;
  const translation = mongolianDestinations[destination.slug];
  if (!translation) {
    throw new Error(`Missing Mongolian translation for ${destination.slug}`);
  }
  return {
    ...destination,
    ...translation,
    aboutText: destination.aboutTextMn ?? translation.aboutText,
    activities:
      destination.activitiesMn === undefined
        ? translation.activities
        : destination.activitiesMn,
    featuredRestaurant:
      destination.featuredRestaurantMn ?? translation.featuredRestaurant,
    contactText: destination.contactTextMn ?? translation.contactText,
    stay:
      destination.stayMn === undefined
        ? translation.stay
        : destination.stayMn,
  };
}
